test('Ctrl+, opens Settings with a segmented theme control and the hidden-files checkbox beside its label', async () => {
  const live = await launch({ file: fixture('settings-polish.md', '# Settings polish\n') })
  await expect(live.win.getByRole('heading', { name: 'Settings polish' })).toBeVisible()
  await live.win.keyboard.press('Control+,')
  await expect(live.win.getByRole('tab', { name: '⚙ Settings', exact: true })).toHaveAttribute('aria-selected', 'true')
  const modes = live.win.getByRole('group', { name: 'Theme mode', exact: true })
  await expect(modes.getByRole('button')).toHaveText(['System', 'Always light', 'Always dark'])
  await modes.getByRole('button', { name: 'Always dark', exact: true }).click()
  await expect(live.win.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(modes.getByRole('button', { name: 'Always dark', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(modes.getByRole('button', { name: 'System', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await live.win.getByRole('button', { name: 'Files', exact: true }).click()
  const gap = await live.win.locator('label.settings-check').evaluate(label => {
    const box = label.querySelector('input')!.getBoundingClientRect(), text = document.createRange()
    text.selectNodeContents(label.lastChild!)
    return { start: box.left - label.getBoundingClientRect().left, between: text.getBoundingClientRect().left - box.right }
  })
  expect(gap.start).toBeLessThan(8)
  expect(gap.between).toBeLessThan(16)
  expect(live.pageErrors).toEqual([])
  expect(await finish(live)).toEqual({ code: 0, signal: null })
})

