import { expect } from '@playwright/test'
import { finish, fixture, launch, recordClipboard, test } from './app'
import { closePackaged, launchPackaged, unrequested } from './packaged'
import { query, ready } from './find-ui'

test('Grid sorts stably, finds in display order and copies full values for ranges, rows and columns', async () => {
  const long = 'a'.repeat(5000) + ' creek'
  const file = fixture('grid-interactions.csv', 'rank,task,notes\r\n10,North,' + long + '\r\n2,South,first creek\r\n2,West,second\r\n')
  const live = await launch({ file })
  // Record the text at the OS boundary in this test process. The user's clipboard is private.
  const clipboard = await recordClipboard(live.app)
  const copied = async () => (await clipboard()).at(-1)?.replace(/\r\n/g, '\n')
  const page = live.win
  const card = page.getByRole('region', { name: 'Reader card 1' })
  const grid = card.getByRole('grid', { name: 'CSV grid' })
  await expect(grid).toHaveAttribute('data-ready', '1', ready)
  const header = grid.getByRole('columnheader', { name: 'rank', exact: true })
  const rows = grid.getByRole('row').filter({ has: page.getByRole('gridcell') })
  await header.focus()
  await page.keyboard.press('Enter')
  await expect(rows.nth(0)).toContainText('South')
  await expect(rows.nth(1)).toContainText('West')
  await expect(rows.nth(2)).toContainText('North')
  await expect(rows.nth(0).getByRole('rowheader')).toHaveText('2')
  await page.keyboard.press('ControlOrMeta+g')
  const goTo = card.getByRole('spinbutton')
  await goTo.fill('3')
  await goTo.press('Enter')
  await expect(rows.nth(1).getByRole('rowheader')).toHaveText('3')
  await expect(rows.nth(1).getByRole('gridcell', { selected: true })).toHaveCount(1)
  await rows.nth(0).getByRole('gridcell', { name: 'first creek', exact: true }).click()
  await page.keyboard.press('Enter')
  const inspector = card.getByRole('dialog', { name: 'Cell value' })
  await expect(inspector.locator('pre')).toHaveText('first creek')
  await inspector.getByRole('button', { name: 'Close value' }).click()
  await rows.nth(0).getByRole('gridcell', { name: 'South', exact: true }).click()
  await page.keyboard.press('Shift+ArrowDown')
  await page.keyboard.press('ControlOrMeta+c')
  await expect.poll(copied).toBe('South\nWest')
  const bar = await query(page, card, 'creek')
  await expect(bar.getByRole('status')).toHaveText('1 of 2', ready)
  await expect(rows.nth(0).locator('[aria-current="true"]')).toContainText('first creek')
  await page.keyboard.press('F3')
  await expect(bar.getByRole('status')).toHaveText('2 of 2')
  await expect(rows.nth(2).locator('[aria-current="true"]')).toBeInViewport()
  await expect(card.locator('.csv-find-excerpt mark')).toHaveText('creek')
  await page.keyboard.press('Escape')
  await header.focus()
  await page.keyboard.press('Space')
  await expect(rows.nth(0)).toContainText('North')
  await expect(rows.nth(1)).toContainText('South')
  await expect(rows.nth(2)).toContainText('West')
  await expect(header).toBeFocused()
  await header.click()
  await expect(rows.nth(0).getByRole('rowheader')).toHaveText('1')
  await rows.nth(0).getByRole('gridcell', { name: 'North', exact: true }).click()
  await page.keyboard.press('Shift+ArrowRight')
  await page.keyboard.press('ControlOrMeta+c')
  await expect.poll(copied).toBe('North\t' + long)
  await rows.nth(1).getByRole('gridcell', { name: 'South', exact: true }).click()
  await page.keyboard.press('Shift+Space')
  await page.keyboard.press('ControlOrMeta+c')
  await expect.poll(copied).toBe('2\tSouth\tfirst creek')
  await rows.nth(2).getByRole('gridcell', { name: 'West', exact: true }).click()
  await page.keyboard.press('Control+Space')
  await page.keyboard.press('ControlOrMeta+c')
  await expect.poll(copied).toBe('task\nNorth\nSouth\nWest')

  await grid.getByRole('columnheader', { name: 'rank', exact: true }).click({ button: 'right' })
  const menu = card.getByRole('menu', { name: 'Grid actions' })
  await menu.getByRole('menuitem', { name: 'Select column', exact: true }).click()
  await expect(menu).toHaveCount(0)
  await page.keyboard.press('ControlOrMeta+c')
  await expect.poll(copied).toBe('rank\n10\n2\n2')
  await rows.nth(2).getByRole('gridcell', { name: 'West', exact: true }).click()
  await page.keyboard.press('Shift+F10')
  await expect(menu.getByRole('menuitem', { name: 'Select row' })).toBeFocused()
  await page.keyboard.press('Enter')
  await page.keyboard.press('ControlOrMeta+c')
  await expect.poll(copied).toBe('2\tWest\tsecond')

  const start = await rows.nth(1).getByRole('gridcell', { name: 'South', exact: true }).boundingBox()
  const end = await rows.nth(1).getByRole('gridcell', { name: 'first creek', exact: true }).boundingBox()
  const outside = await card.getByRole('heading', { name: 'grid-interactions.csv' }).boundingBox()
  if (!start || !end || !outside) throw new Error('Missing drag target')
  await page.mouse.move(start.x + 8, start.y + 8)
  await page.mouse.down()
  await page.mouse.move(end.x + 8, end.y + 8, { steps: 4 })
  await page.mouse.move(outside.x + 3, outside.y + 3)
  await page.mouse.up()
  await rows.nth(2).getByRole('gridcell', { name: 'West', exact: true }).hover()
  await expect(rows.nth(1).getByRole('gridcell', { selected: true })).toHaveCount(2)
  await expect(rows.nth(2).getByRole('gridcell', { selected: true })).toHaveCount(0)

  await header.click()
  await expect(rows.nth(0)).toContainText('South')
  await card.getByRole('tab', { name: 'Raw', exact: true }).click()
  await expect(card.locator('.vl-scroller')).toBeVisible()
  await card.getByRole('tab', { name: 'Grid', exact: true }).click()
  await expect(grid).toHaveAttribute('data-ready', '1', ready)
  const reopened = await query(page, card, 'first creek')
  await expect(reopened.getByRole('status')).toHaveText('1 of 1')
  await expect(grid.locator('[aria-current="true"]')).toContainText('first creek')
  expect(live.pageErrors).toEqual([])
  expect(await finish(live)).toEqual({ code: 0, signal: null })
})

test('packaged Grid Find jumps to a cell outside both viewport axes', async () => {
  const width = 30
  const header = Array.from({ length: width }, (_, col) => 'field' + col).join(',')
  const data = Array.from({ length: 90 }, (_, row) => Array.from({ length: width }, (_, col) =>
    row === 84 && col === 27 ? 'deep water marker' : String(row * width + col)).join(','))
  const file = fixture('grid-search-distant.csv', [header, ...data].join('\n'))
  const live = await launchPackaged({ cdp: true, file })
  const page = live.page!
  const card = page.getByRole('region', { name: 'Reader card 1' })
  const grid = card.getByRole('grid', { name: 'CSV grid' })
  await expect(grid).toHaveAttribute('data-ready', '1', ready)
  const hit = grid.getByRole('gridcell', { name: 'deep water marker' })
  await expect(hit).toHaveCount(0)
  const bar = await query(page, card, 'water marker')
  await expect(bar.getByRole('status')).toHaveText('1 of 1', ready)
  await expect(hit).toBeInViewport(ready)
  await expect(hit).toHaveAttribute('aria-current', 'true')
  await expect(hit).toHaveAttribute('aria-colindex', '29')
  const exit = await closePackaged(live)
  expect(unrequested(live, exit)).toEqual([])
})
