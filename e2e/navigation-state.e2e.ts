import { expect } from '@playwright/test'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { FIXTURES, debugStats, finish, fixture, launch, test, visibleRows, waitIndexed, waitOpen } from './app'

test('failed Back preserves the mounted preview and history until its target can reopen', async () => {
  test.skip(process.platform !== 'win32', 'local capability backend is currently Windows-only')
  const directory = join(FIXTURES, 'navigation-failure')
  mkdirSync(directory, { recursive: true })
  const a = fixture('navigation-failure/A.md', '# A\n\n[Go to B](B.md)\n')
  fixture('navigation-failure/B.md', '# B\n\nSource stays visible.\n')
  const start = fixture('navigation-failure/start.md', '# Start\n\n[Preview A](A.md)\n')
  const l = await launch({ file: start })
  const { win } = l
  await expect(win.locator('.md-scroller')).toHaveAttribute('data-ready', '1')
  await win.getByRole('link', { name: 'Preview A' }).click()
  const preview = win.getByRole('dialog', { name: 'Link preview' })
  await preview.getByRole('link', { name: 'Go to B' }).click()
  await expect(preview.locator('.card-name')).toHaveText('B.md')
  await expect(preview.locator('.md-scroller')).toHaveAttribute('data-ready', '1')
  await preview.locator('.md-scroller').evaluate(el => { el.dataset.sourceIdentity = 'kept' })
  rmSync(a)
  await preview.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(preview.locator('.banner')).toContainText('Cannot go Back')
  await expect(preview.locator('.card-name')).toHaveText('B.md')
  await expect(preview.locator('.md-scroller')).toHaveAttribute('data-source-identity', 'kept')
  await expect(preview.getByRole('button', { name: 'Back', exact: true })).toBeEnabled()
  writeFileSync(a, '# A again\n')
  await preview.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(preview.locator('.card-name')).toHaveText('A.md')
  expect(l.pageErrors).toEqual([])
  await finish(l)
})

test('closing a derived tab retains only a route; Clear releases it', async () => {
  test.skip(process.platform !== 'win32', 'local capability backend is currently Windows-only')
  const directory = join(FIXTURES, 'navigation-route-cleanup')
  mkdirSync(directory, { recursive: true })
  const a = fixture('navigation-route-cleanup/A.md', '# A\n\n[Go to B](B.txt)\n')
  fixture('navigation-route-cleanup/B.txt', 'Derived text\n')
  const l = await launch({ hooks: true, file: a })
  const { win } = l
  await expect(win.locator('.md-scroller')).toHaveAttribute('data-ready', '1')
  await win.getByRole('link', { name: 'Go to B' }).click({ modifiers: ['Control'] })
  await expect(win.locator('.card-name')).toHaveText('B.txt')
  await waitOpen(win)
  await win.getByRole('button', { name: 'Close B.txt', exact: true }).click()
  await expect(win.locator('.card-name')).toHaveText('A.md')
  await expect.poll(async () => ({ docs: (await debugStats(win)).docs, tickets: (await debugStats(win)).saved.tickets })).toEqual({ docs: 1, tickets: 1 })
  await win.getByRole('button', { name: 'Menu', exact: true }).click()
  await win.getByRole('menuitem', { name: 'Clear recently closed tabs', exact: true }).click()
  await expect.poll(async () => (await debugStats(win)).saved.tickets).toBe(0)
  expect(l.pageErrors).toEqual([])
  await finish(l)
})

test('Reopen clamps a saved Raw anchor when the file became shorter', async () => {
  const file = fixture('navigation-shorter.txt', 'Before shrink\n'.repeat(1000))
  const l = await launch({ file })
  const { win } = l
  await waitOpen(win)
  await waitIndexed(win)
  await win.locator('.vl-scroller').evaluate(el => { el.scrollTop = 7000 })
  await expect.poll(async () => (await visibleRows(win))[0]?.line ?? 0).toBeGreaterThan(100)
  await win.getByRole('button', { name: 'Close navigation-shorter.txt', exact: true }).click()
  await expect(win.getByRole('button', { name: /^Open file…/ })).toBeVisible()
  writeFileSync(file, 'one\ntwo\nthree')
  await win.keyboard.press(process.platform === 'darwin' ? 'Meta+Shift+T' : 'Control+Shift+T')
  await waitOpen(win)
  expect(await waitIndexed(win)).toBe(3)
  await expect.poll(async () => (await visibleRows(win)).map(row => row.text)).toEqual(['one', 'two', 'three'])
  expect(l.pageErrors).toEqual([])
  await finish(l)
})
